"""M51 Aufgabe 1: AWS Polly Sample-Generierung.

Liest data/texts.json, fragt Polly describe_voices() ab, synthetisiert
fuer jede Voice × unterstützte EU-Sprache × 3 Varianten ein MP3-Sample.
Output:
  audio/aws/{voice_id}/{lang}_{variant}.mp3
  data/samples.json (append-safe)

Keys aus /root/hermes-workspace/devbrain/.env/aws.env
Mutagen ID3-Tags fuer Attribution (Ghostforge / CC BY 4.0).
"""
